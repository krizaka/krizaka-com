export type BrandFilmShot = (typeof BRAND_FILM.shots)[number];

/** True when every file of the vertical cut is on the CDN (`has` is lib/cdn.ts's onCdn). */
export const hasTallCut = (has: (path: string) => boolean): boolean =>
  ["mp4", "jpg"].every((ext) => has(`${BRAND_FILM.tall}.${ext}`));

/** True when the visitor asked for less (reduced motion, or Save-Data): the film then waits on its poster, never autoplays. */
export function prefersStill(viewer: {
  matchMedia?: (query: string) => { matches: boolean };
  /** The browser's navigator: `connection.saveData` is not in every engine nor in the DOM types, so it is read loosely. */
  navigator?: object;
}): boolean {
  const connection = (viewer.navigator as { connection?: { saveData?: boolean } } | undefined)?.connection;
  return Boolean(viewer.matchMedia?.("(prefers-reduced-motion: reduce)").matches || connection?.saveData);
}
